import { boolean, index, integer, jsonb, pgTable, text, timestamp, uuid } from "drizzle-orm/pg-core";

export const meditationSessions = pgTable(
  "meditation_sessions",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    technique: text("technique").notNull(),
    title: text("title").notNull(),
    durationSeconds: integer("duration_seconds").notNull(),
    completed: boolean("completed").notNull().default(true),
    moodBefore: integer("mood_before"),
    moodAfter: integer("mood_after"),
    notes: text("notes"),
    createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
  },
  (t) => [
    index("sessions_created_idx").on(t.createdAt),
    index("sessions_technique_idx").on(t.technique),
  ]
);

export const journalEntries = pgTable(
  "journal_entries",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    title: text("title").notNull(),
    content: text("content").notNull(),
    mood: text("mood"),
    prompt: text("prompt"),
    gratitude: text("gratitude"),
    createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).defaultNow().notNull(),
  },
  (t) => [index("journal_created_idx").on(t.createdAt)]
);

export const meditationTechniques = pgTable(
  "meditation_techniques",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    slug: text("slug").notNull().unique(),
    name: text("name").notNull(),
    pali: text("pali"),
    tradition: text("tradition").notNull(),
    level: text("level").notNull(),
    category: text("category").notNull(),
    durations: jsonb("durations").$type<number[]>().notNull(),
    description: text("description").notNull(),
    essence: text("essence").notNull(),
    instructions: jsonb("instructions").$type<string[]>().notNull(),
    benefits: jsonb("benefits").$type<string[]>().notNull(),
    source: text("source").notNull(),
    color: text("color").notNull(),
    symbol: text("symbol").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
  },
  (t) => [
    index("tech_slug_idx").on(t.slug),
    index("tech_tradition_idx").on(t.tradition),
    index("tech_level_idx").on(t.level),
    index("tech_category_idx").on(t.category),
    index("tech_name_idx").on(t.name),
    // composite for filtered browsing (tradition × category × level)
    index("tech_browse_idx").on(t.tradition, t.category, t.level),
  ]
);

// Agentic plans — 7-day programs generated by Bodhi Guide, saved by the user
export const practicePlans = pgTable(
  "practice_plans",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    title: text("title").notNull(),
    goal: text("goal"),
    minutesPerDay: integer("minutes_per_day"),
    level: text("level"),
    // [{ day, slug, name, minutes, focus }]
    days: jsonb("days").$type<{ day: number; slug: string; name: string; minutes: number; focus: string }[]>().notNull(),
    active: boolean("active").notNull().default(false),
    createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
  },
  (t) => [index("plans_created_idx").on(t.createdAt)]
);

export type MeditationSession = typeof meditationSessions.$inferSelect;
export type NewMeditationSession = typeof meditationSessions.$inferInsert;
export type JournalEntry = typeof journalEntries.$inferSelect;
export type NewJournalEntry = typeof journalEntries.$inferInsert;
export type MeditationTechnique = typeof meditationTechniques.$inferSelect;
export type NewMeditationTechnique = typeof meditationTechniques.$inferInsert;
export type PracticePlan = typeof practicePlans.$inferSelect;
export type NewPracticePlan = typeof practicePlans.$inferInsert;
